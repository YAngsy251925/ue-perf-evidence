#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""session_drift.py — M3.0 常驻会话实测：单次采集成本 + run 间漂移（PLAN §9-M3.0）

流程：启动一次常驻编辑器（控制端口）→ ping 等就绪 → 连续 K 段采集
（exec Trace.File <seg_k.utrace> → sleep → exec Trace.Stop → 等文件收尾）→ quit →
逐段 probe 导出 → 报告每段的 Game Frame interval p50、每段成本、组内 CV。
判定（Q1 噪声门）：CV < 3% → 常驻模式可用于 agent 循环的 AB 对比。

用法（仓库根目录）：python perfctl.py session-drift [--segments 6] [--duration 20] [--port 19860]
"""
import argparse
import json
import os
import socket
import subprocess
import sys
import time

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
UPROJECT = os.path.join(REPO, "host", "TraceDigestProbe", "TraceDigestProbe.uproject")
DEFAULT_UE_ROOT = r"D:\Epic\Games\UE_5.8"
PORT = 19860
CHANNELS = "cpu,frame,gpu,bookmark"
READY_MARK = "Engine is initialized"


def control_send(command, timeout=10):
    """发一行命令，收一行回复，关连接。返回回复文本；失败抛 OSError。"""
    with socket.create_connection(("127.0.0.1", PORT), timeout=timeout) as s:
        s.settimeout(timeout)
        s.sendall((command + "\n").encode("ascii"))
        buf = b""
        while not buf.endswith(b"\n"):
            chunk = s.recv(256)
            if not chunk:
                break
            buf += chunk
    return buf.decode("ascii", errors="replace").strip()


def wait_ready(log_path, proc, startup_budget, port):
    t0 = time.time()
    while time.time() - t0 < startup_budget:
        if proc.poll() is not None:
            sys.exit("[error] editor exited during startup (exit=%s)" % proc.returncode)
        if os.path.isfile(log_path):
            with open(log_path, encoding="utf-8-sig", errors="replace") as f:
                if READY_MARK in f.read():
                    ready_s = time.time() - t0
                    break
        time.sleep(2)
    else:
        sys.exit("[error] STARTUP_TIMEOUT: no ready mark within %ds" % startup_budget)
    while time.time() - t0 < startup_budget + 15:
        try:
            if control_send("ping") == "pong":
                return ready_s
        except OSError:
            pass
        time.sleep(1)
    sys.exit("[error] control port did not answer ping after ready")


def wait_stable(path, timeout=30, stable_for=2):
    t0 = time.time()
    last = -1
    last_change = time.time()
    while time.time() - t0 < timeout:
        size = os.path.getsize(path) if os.path.isfile(path) else -1
        if size != last:
            last, last_change = size, time.time()
        elif time.time() - last_change >= stable_for:
            return time.time() - t0
        time.sleep(1)
    return timeout


def main(argv=None) -> int:
    for stream in (sys.stdout, sys.stderr):  # PLAN 7.4 E4: UTF-8 output without relying on PYTHONUTF8
        stream.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description="M3.0 常驻会话实测")
    ap.add_argument("--segments", type=int, default=6)
    ap.add_argument("--duration", type=int, default=20, help="每段采集窗口（秒）")
    ap.add_argument("--port", type=int, default=PORT)
    ap.add_argument("--ue-root", default=None)
    a = ap.parse_args(argv)
    ue_root = a.ue_root or os.environ.get("UE_ROOT") or DEFAULT_UE_ROOT
    run_dir = os.path.abspath(os.path.join(REPO, "runs", "m3_0", "session"))
    os.makedirs(run_dir, exist_ok=True)
    exe = os.path.join(ue_root, "Engine", "Binaries", "Win64", "UnrealEditor-Cmd.exe")
    log = os.path.join(run_dir, "engine.log")
    if os.path.isfile(log):
        os.remove(log)
    args = [UPROJECT, "/Engine/Maps/Entry", "-game", "-nullrhi", "-windowed", "-resx=960", "-resy=540",
            "-unattended", "-nosplash", "-nosound", "-statnamedevents",
            "PerfEvidence.ControlPort=%d" % a.port, "-stdout", '-ABSLOG="%s"' % log]
    bat = os.path.join(run_dir, "launch_session.bat")
    with open(bat, "w", encoding="ascii", newline="") as f:
        f.write("@echo off\r\nrem generated by perfctl session-drift (M3.0); do not edit\r\n")
        f.write('"%s" %s\r\necho EXITCODE=%%ERRORLEVEL%%\r\n' % (exe, " ".join(args)))
    print("[session] launching persistent editor via launch_session.bat (control port %d) ..." % a.port)
    # 与 capture 同路径：cmd /c bat + 新控制台。注意：真正让编辑器卡在模块加载后段的
    # 是宿主模块在静态初始化里建控制口监听（PLAN P17，加载器锁互等），已修；
    # 这里保留 cmd /c 只是为了和 measure profile 的启动方式一致。
    proc = subprocess.Popen(["cmd", "/c", bat], creationflags=subprocess.CREATE_NEW_CONSOLE,
                            stdin=subprocess.DEVNULL)
    ready_s = wait_ready(log, proc, 1800, a.port)
    print("[session] ready in %.1fs; control port alive" % ready_s)

    segments = []
    for k in range(1, a.segments + 1):
        seg_path = os.path.join(run_dir, "seg_%d.utrace" % k)
        if os.path.isfile(seg_path):
            os.remove(seg_path)
        t0 = time.time()
        reply = control_send("exec Trace.File %s %s" % (seg_path.replace("\\", "/"), CHANNELS))
        if reply != "queued":
            print("[session] segment %d: start refused (%r)" % (k, reply))
            break
        time.sleep(a.duration)
        reply = control_send("exec Trace.Stop")
        finalize_s = wait_stable(seg_path)
        total = time.time() - t0
        size_mb = os.path.getsize(seg_path) / 1e6 if os.path.isfile(seg_path) else 0
        overhead = total - a.duration
        segments.append({"seg": k, "path": seg_path, "wall_s": round(total, 1),
                         "overhead_s": round(overhead, 1), "finalize_s": round(finalize_s, 1),
                         "size_mb": round(size_mb, 1)})
        print("[session] seg %d: wall %.1fs (overhead %.1fs), finalize %.1fs, %.1f MB"
              % (k, total, overhead, finalize_s, size_mb))
    control_send("quit")
    proc.wait(timeout=60)

    print("[session] exporting %d segments for drift stats ..." % len(segments))
    from pipeline.extract import insights_export
    p50s = []
    for seg in segments:
        outdir = os.path.join(run_dir, "seg_%d_export" % seg["seg"])
        rc = insights_export.main(["probe", seg["path"], "--out", outdir])
        if rc != 0:
            print("[session] export failed for seg %d" % seg["seg"])
            continue
        from pipeline.caliber.frame_probe import load_frame_series, pick_reference
        ref = pick_reference(load_frame_series(outdir))
        frames = ref["frames"] if ref else []
        if len(frames) < 2:
            continue
        intervals = sorted((frames[i][0] - frames[i - 1][0]) * 1000.0 for i in range(1, len(frames)))
        p50 = intervals[len(intervals) // 2]
        p50s.append(p50)
        seg["interval_p50_ms"] = round(p50, 3)
        seg["frames"] = len(frames)
        print("[session] seg %d: frames=%d interval p50=%.3fms" % (seg["seg"], len(frames), p50))

    result = {"schema": "perf-session/0", "ready_s": round(ready_s, 1),
              "segments": segments,
              "drift": None}
    # 首段丢弃：M3.0 实测首段 p50 明显偏高（warm-up，见 PLAN §7.3 / §7.3.1），
    # 常驻会话的噪声基线只按稳态段算。
    steady = p50s[1:] if len(p50s) >= 4 else p50s
    if len(steady) >= 3:
        mean = sum(steady) / len(steady)
        var = sum((x - mean) ** 2 for x in steady) / (len(steady) - 1)
        std = var ** 0.5
        cv = 100.0 * std / mean
        verdict = "usable" if cv < 3.0 else "too noisy"
        result["drift"] = {"p50s_ms": [round(x, 3) for x in steady], "mean": round(mean, 3),
                           "std": round(std, 3), "cv_pct": round(cv, 2), "verdict": verdict,
                           "dropped_warmup_segments": len(p50s) - len(steady),
                           "raw_p50s_ms": [round(x, 3) for x in p50s]}
        print("[session] DRIFT: steady p50s=%s mean=%.3f std=%.3f CV=%.2f%% -> %s (dropped %d warm-up)"
              % (["%.3f" % x for x in steady], mean, std, cv, verdict, len(p50s) - len(steady)))
    with open(os.path.join(run_dir, "session_drift.json"), "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=1)
    print("[ok] %s" % os.path.join(run_dir, "session_drift.json"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
